import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const source = readFileSync("src/app/lib/betaVisit.ts", "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const storage = new Map();
let now = 1000; let sequence = 0;
const context = { exports: {}, sessionStorage: { getItem: (k) => storage.get(k), setItem: (k,v) => storage.set(k,v) }, Date: { now: () => now }, crypto: { randomUUID: () => `session-${++sequence}` } };
vm.runInNewContext(compiled, context);
const { captureBetaVisit } = context.exports;
const first = captureBetaVisit();
assert.equal(first.sessionId, captureBetaVisit().sessionId);
assert.deepEqual(Object.keys(first), ["sessionId"]);
now += 31 * 60 * 1000;
assert.notEqual(first.sessionId, captureBetaVisit().sessionId);
storage.set("rion-beta-visit", "{broken");
assert.ok(captureBetaVisit().sessionId);
const sql = readFileSync("docs/sql/supabase-beta-page-visits.sql", "utf8");
for (const clause of ["enable row level security", "from public, anon, authenticated", "primary key (session_id, recruitment_round_id)"]) assert.ok(sql.includes(clause));
assert.ok(!sql.includes("utm_"));
const ops = readFileSync("src/app/api/ops/beta-visits/route.ts", "utf8");
assert.ok(ops.includes('requireOpsUser(req, admin, ["master", "support"])'));
assert.equal((ops.match(/eq\("recruitment_round_id", roundId\)/g)||[]).length, 2);
const ingest = readFileSync("src/app/api/beta-visits/route.ts", "utf8");
assert.ok(ingest.includes("ignoreDuplicates: true"));
assert.ok(ingest.includes('req.headers.get("origin") !== req.nextUrl.origin'));
assert.ok(ingest.includes("raw.length > 2048"));
const ui = readFileSync("src/app/ops/beta-applications/OpsBetaVisitStats.tsx", "utf8");
assert.ok(!ui.includes("utm_") && !ui.includes("<table"));
assert.ok(readFileSync("src/app/ops/beta-applications/OpsBetaRecruitmentRounds.tsx", "utf8").includes("roundId={current.id}"));
console.log("PASS: compact round counts, no attribution, refresh deduplication, expiry and OPS/DB protection");
